export function getLessonsByCourse(courseSlug: string): Lesson[] {
  return lessons.filter((l) => l.course === courseSlug);
}

export function getLesson(courseSlug: string, id: number): Lesson | undefined {
  return lessons.find((l) => l.course === courseSlug && l.id === id);
}

export function getNextLesson(
  courseSlug: string,
  currentId: number
): Lesson | undefined {
  const courseLessons = getLessonsByCourse(courseSlug);
  const index = courseLessons.findIndex((l) => l.id === currentId);
  return index >= 0 ? courseLessons[index + 1] : undefined;
}
